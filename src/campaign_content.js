export function summarizeCampaignScene(page) {
  if (!page) {
    return 'Сцена не выбрана.';
  }
  const head = page.speaker ? `${page.speaker}: ` : '';
  const text = Array.isArray(page.text) ? page.text[0] ?? '' : page.text ?? '';
  return `${head}${text}`;
}
