function titlePage(title, subtitle, text, extra = {}) {
  return {
    kind: 'title-card',
    title,
    subtitle,
    text: Array.isArray(text) ? text : [text],
    ...extra,
  };
}

function narrationPage(title, text, extra = {}) {
  return {
    kind: 'narration',
    title,
    text: Array.isArray(text) ? text : [text],
    ...extra,
  };
}

function dialoguePage(speaker, text, extra = {}) {
  return {
    kind: 'dialogue',
    speaker,
    title: extra.title ?? speaker,
    text: Array.isArray(text) ? text : [text],
    ...extra,
  };
}

function resultPage(title, text, extra = {}) {
  return {
    kind: 'result',
    title,
    text: Array.isArray(text) ? text : [text],
    ...extra,
  };
}

