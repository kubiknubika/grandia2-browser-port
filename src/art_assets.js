export function unitArtPathForFighter(fighter) {
  if (!fighter) {
    return null;
  }
  const key = fighter.sourceKey ?? fighter.id ?? null;
  if (UNIT_ART[key]) {
    return UNIT_ART[key];
  }
  const camelKey = String(key ?? '').replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
  return UNIT_ART[camelKey] ?? null;
}

export function battlefieldArtPath(theme) {
  return BATTLEFIELD_ART[theme] ?? null;
}

export function campaignBackdropPathForLocation(location) {
  if (!location) {
    return null;
  }
  return LOCATION_TO_REGION_ART[location.id] ?? null;
}
